package netif

import (
	"net/netip"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	const in = `# Generated by NetworkManager
; another comment style
search corp.example ad.corp.example.
domain corp.example
nameserver 10.0.0.53
nameserver 10.0.0.54 # inline comment
nameserver fe80::1%eth0
nameserver not-an-address
options edns0 trust-ad
`
	rc := ParseResolvConf(strings.NewReader(in))

	want := []netip.Addr{
		netip.MustParseAddr("10.0.0.53"),
		netip.MustParseAddr("10.0.0.54"),
		netip.MustParseAddr("fe80::1"),
	}
	if len(rc.Nameservers) != len(want) {
		t.Fatalf("nameservers = %v, want %v", rc.Nameservers, want)
	}
	for i := range want {
		if rc.Nameservers[i] != want[i] {
			t.Errorf("nameserver[%d] = %v, want %v", i, rc.Nameservers[i], want[i])
		}
	}
	if rc.Domain != "corp.example" {
		t.Errorf("domain = %q", rc.Domain)
	}
	if len(rc.Search) != 2 || rc.Search[0] != "corp.example" || rc.Search[1] != "ad.corp.example" {
		t.Errorf("search = %v, want [corp.example ad.corp.example] with the trailing dot stripped", rc.Search)
	}
	if rc.Stub {
		t.Error("Stub set although the servers are not loopback")
	}
}

func TestParseResolvConfStub(t *testing.T) {
	rc := ParseResolvConf(strings.NewReader("nameserver 127.0.0.53\noptions edns0\n"))
	if !rc.Stub {
		t.Error("127.0.0.53 should be recognised as a stub resolver")
	}
}

func TestParseResolvConfEmpty(t *testing.T) {
	rc := ParseResolvConf(strings.NewReader("\n\n# nothing here\n"))
	if len(rc.Nameservers) != 0 || len(rc.Search) != 0 || rc.Stub {
		t.Errorf("unexpected result %+v", rc)
	}
}

// LoadResolvConf must prefer systemd-resolved's upstream servers over the 127.0.0.53 stub
// that /etc/resolv.conf points at.
func TestLoadResolvConfPrefersUpstreamOverStub(t *testing.T) {
	root := t.TempDir()
	write := func(p, content string) {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("run/systemd/resolve/resolv.conf", "nameserver 10.0.0.53\nsearch corp.example\n")
	write("etc/resolv.conf", "nameserver 127.0.0.53\nsearch corp.example\n")

	rc := LoadResolvConf(root, ResolvConfPaths)
	if len(rc.Nameservers) != 1 || rc.Nameservers[0] != netip.MustParseAddr("10.0.0.53") {
		t.Fatalf("nameservers = %v, want only the upstream 10.0.0.53", rc.Nameservers)
	}
	if len(rc.Search) != 1 || rc.Search[0] != "corp.example" {
		t.Errorf("search = %v (should be de-duplicated across files)", rc.Search)
	}
}

func TestLoadResolvConfStubOnly(t *testing.T) {
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, "etc"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "etc/resolv.conf"), []byte("nameserver 127.0.0.53\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	rc := LoadResolvConf(root, ResolvConfPaths)
	if len(rc.Nameservers) != 1 || rc.Nameservers[0] != SystemdStubResolver || !rc.Stub {
		t.Fatalf("got %+v, want the stub reported as a last resort", rc)
	}
}

func TestLoadResolvConfMissing(t *testing.T) {
	rc := LoadResolvConf(t.TempDir(), ResolvConfPaths)
	if len(rc.Nameservers) != 0 {
		t.Errorf("nameservers = %v, want none", rc.Nameservers)
	}
}
