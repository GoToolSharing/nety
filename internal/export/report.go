func writeMarkdown(w io.Writer, d model.MissionData) error {
	sum := buildSummary(d)
	names := networkNames(d)
	byHost := servicesByHost(d)

	p := func(format string, args ...any) error {
		_, err := fmt.Fprintf(w, format, args...)
		return err
	}

	title := d.Mission.Name
	if d.Mission.Client != "" {
		title = fmt.Sprintf("%s - %s", d.Mission.Client, d.Mission.Name)
	}
	if err := p("# Internal network review - %s\n\n", title); err != nil {
		return err
	}
	if d.Mission.Description != "" {
		if err := p("%s\n\n", d.Mission.Description); err != nil {
			return err
		}
	}
	if err := p("_Generated by NETY %s on %s._\n\n",
		config.Version, d.ExportedAt.Format("2006-01-02 15:04 MST")); err != nil {
		return err
	}

	// Summary.
	if err := p("## Summary\n\n"); err != nil {
		return err
	}
	if err := p("| | |\n|---|---|\n"); err != nil {
		return err
	}
	rows := [][2]string{
		{"Networks reviewed", itoa(sum.Networks)},
		{"Live hosts", itoa(sum.Hosts)},
		{"Open services", itoa(sum.Services)},
		{"Distinct machines (assets)", itoa(sum.Assets)},
		{"Findings", itoa(sum.Findings)},
	}
	if sum.ReachTested > 0 {
		rows = append(rows,
			[2]string{"Segmentation tests run", itoa(sum.ReachTested)},
			[2]string{"Flows that crossed a boundary", itoa(sum.ReachOK)})
	}
	for _, r := range rows {
		if err := p("| %s | %s |\n", r[0], r[1]); err != nil {
			return err
		}
	}
	if err := p("\n"); err != nil {
		return err
	}

	if sum.Findings > 0 {
		if err := p("Findings by severity: "); err != nil {
			return err
		}
		var parts []string
		for _, sev := range []model.Severity{model.SevCritical, model.SevHigh, model.SevMedium, model.SevLow, model.SevInfo} {
			if n := sum.BySeverity[sev]; n > 0 {
				parts = append(parts, fmt.Sprintf("**%s** %d", strings.ToUpper(string(sev)), n))
			}
		}
		if err := p("%s\n\n", strings.Join(parts, " · ")); err != nil {
			return err
		}
	}

	// Networks.
	if err := p("## Networks\n\n| Network | VLAN | Prefixes | Gateway | Hosts | Services |\n|---|---|---|---|---|---|\n"); err != nil {
		return err
	}
	hostsPerNet := map[int64]int{}
	svcPerNet := map[int64]int{}
	for _, h := range d.Hosts {
		hostsPerNet[h.NetworkID]++
	}
	for _, s := range d.Services {
		svcPerNet[s.NetworkID]++
	}
	for _, n := range d.Networks {
		vlan := "-"
		if n.VLANID != 0 {
			vlan = itoa(n.VLANID)
		}
		if err := p("| %s | %s | %s | %s | %d | %d |\n",
			mdEscape(n.Name), vlan, strings.Join(n.Prefixes, ", "),
			firstNonEmpty(n.Gateway, "-"), hostsPerNet[n.ID], svcPerNet[n.ID]); err != nil {
			return err
		}
	}
	if err := p("\n"); err != nil {
		return err
	}

	// Switch-port observations, which are findings in themselves.
	for _, n := range d.Networks {
		if len(n.L2.Neighbors) == 0 && !n.L2.DTPSeen {
			continue
		}
		if err := p("### Switch port - %s\n\n", mdEscape(n.Name)); err != nil {
			return err
		}
		if n.L2.DTPSeen {
			if err := p("> The port negotiates trunking (DTP mode `%s`). A trunk can likely be obtained from this socket, which would defeat the VLAN separation.\n\n", n.L2.DTPMode); err != nil {
				return err
			}
		}
		for _, nb := range n.L2.Neighbors {
			if err := p("- **%s** via %s - port `%s`%s%s\n",
				mdEscape(nb.DeviceID), strings.ToUpper(nb.Protocol), nb.PortID,
				optional(", platform ", nb.Platform), optional(", mgmt ", nb.MgmtAddress)); err != nil {
				return err
			}
		}
		if n.L2.NativeVLAN != 0 {
			if err := p("- Native VLAN: %d\n", n.L2.NativeVLAN); err != nil {
				return err
			}
		}
		if n.L2.VoiceVLAN != 0 {
			if err := p("- Voice VLAN: %d\n", n.L2.VoiceVLAN); err != nil {
				return err
			}
		}
		if err := p("\n"); err != nil {
			return err
		}
	}

	// Segmentation matrix.
	if len(d.Matrix) > 0 {
		if err := p("## Segmentation matrix\n\nEach cell shows how many of the services tested from the source network were reachable.\n\n"); err != nil {
			return err
		}
		ids := networkIDs(d)
		header := "| source \\ target |"
		sep := "|---|"
		for _, id := range ids {
			header += " " + mdEscape(netName(names, id)) + " |"
			sep += "---|"
		}
		if err := p("%s\n%s\n", header, sep); err != nil {
			return err
		}
		cells := matrixIndex(d)
		for _, src := range ids {
			row := "| **" + mdEscape(netName(names, src)) + "** |"
			for _, dst := range ids {
				row += " " + mdCell(src, dst, cells) + " |"
			}
			if err := p("%s\n", row); err != nil {
				return err
			}
		}
		if err := p("\n"); err != nil {
			return err
		}

		// The detail that matters: what actually crossed.
		crossed := filter(d.Reach, func(r model.ReachResult) bool { return r.Status == model.ReachOpen })
		if len(crossed) > 0 {
			if err := p("### Flows that crossed the segmentation\n\n| From | To | Service | Technique |\n|---|---|---|---|\n"); err != nil {
				return err
			}
			services := serviceIndex(d)
			for _, r := range crossed {
				svc := ""
				if s, ok := services[r.TargetServiceID]; ok {
					svc = firstNonEmpty(serviceLabel(s), s.Name)
				}
				target := fmt.Sprintf("%s:%d/%s", r.IP, r.Port, r.Protocol)
				if r.Port == 0 {
					target = r.IP
				}
				if err := p("| %s | %s | %s | `%s` |\n",
					mdEscape(netName(names, r.SourceNetworkID)),
					target, mdEscape(svc), r.Technique); err != nil {
					return err
				}
			}
			if err := p("\n"); err != nil {
				return err
			}
		}
	}

	// Findings.
	if len(d.Findings) > 0 {
		if err := p("## Findings\n\n"); err != nil {
			return err
		}
		for _, f := range d.Findings {
			loc := f.IP
			if f.Port != 0 {
				loc = fmt.Sprintf("%s:%d/%s", f.IP, f.Port, f.Protocol)
			}
			if err := p("### [%s] %s - %s\n\n", strings.ToUpper(string(f.Severity)), mdEscape(f.Title), loc); err != nil {
				return err
			}
			if f.Description != "" {
				if err := p("%s\n\n", f.Description); err != nil {
					return err
				}
			}
			if f.Evidence != "" {
				if err := p("```\n%s\n```\n\n", strings.TrimSpace(f.Evidence)); err != nil {
					return err
				}
			}
			if f.Remediation != "" {
				if err := p("**Remediation.** %s\n\n", f.Remediation); err != nil {
					return err
				}
			}
			if len(f.References) > 0 {
				if err := p("References: %s\n\n", strings.Join(f.References, ", ")); err != nil {
					return err
				}
			}
		}
	}

	// Inventory.
	if err := p("## Inventory\n\n"); err != nil {
		return err
	}
	for _, n := range d.Networks {
		hosts := filter(d.Hosts, func(h model.Host) bool { return h.NetworkID == n.ID })
		if len(hosts) == 0 {
			continue
		}
		if err := p("### %s\n\n", mdEscape(n.Name)); err != nil {
			return err
		}
		for _, h := range hosts {
			label := hostLabel(h)
			extra := ""
			if h.OS != "" {
				extra = " - " + h.OS
			}
			if h.Vendor != "" {
				extra += " - " + h.Vendor
			}
			if err := p("#### %s (%s)%s\n\n", mdEscape(label), h.IP, mdEscape(extra)); err != nil {
				return err
			}
			services := byHost[h.ID]
			if len(services) == 0 {
				if err := p("_No open port found._\n\n"); err != nil {
					return err
				}
				continue
			}
			if err := p("| Port | Service | Product | Details |\n|---|---|---|---|\n"); err != nil {
				return err
			}
			for _, s := range services {
				details := serviceDetails(s)
				if err := p("| %d/%s | %s | %s | %s |\n",
					s.Port, s.Protocol, mdEscape(firstNonEmpty(s.Name, "unknown")),
					mdEscape(serviceLabel(s)), mdEscape(details)); err != nil {
					return err
				}
			}
			if err := p("\n"); err != nil {
				return err
			}
		}
	}

	// Assets.
	if len(d.Assets) > 0 {
		if err := p("## Machines (stable identities)\n\n| Machine | Type | OS | Addresses | Identified by |\n|---|---|---|---|---|\n"); err != nil {
			return err
		}
		for _, a := range d.Assets {
			var ips []string
			for _, ip := range a.IPs {
				ips = append(ips, fmt.Sprintf("%s (%s)", ip.IP, netName(names, ip.NetworkID)))
			}
			var keys []string
			for _, k := range a.Keys {
				if k.Confidence >= 70 {
					keys = append(keys, string(k.Kind))
				}
			}
			if err := p("| %s | %s | %s | %s | %s |\n",
				mdEscape(a.Label), a.Kind, mdEscape(a.OS),
				mdEscape(strings.Join(ips, ", ")), strings.Join(dedupe(keys), ", ")); err != nil {
				return err
			}
		}
		if err := p("\n"); err != nil {
			return err
		}
	}
	return nil
}

func serviceDetails(s model.Service) string {
	var parts []string
	if s.HTTP != nil {
		if s.HTTP.Title != "" {
			parts = append(parts, `"`+oneLine(s.HTTP.Title, 60)+`"`)
		}
		if s.HTTP.StatusCode != 0 {
			parts = append(parts, fmt.Sprintf("HTTP %d", s.HTTP.StatusCode))
		}
		if len(s.HTTP.Technologies) > 0 {
			parts = append(parts, strings.Join(s.HTTP.Technologies, "/"))
		}
		if len(s.HTTP.AuthSchemes) > 0 {
			parts = append(parts, "auth: "+strings.Join(s.HTTP.AuthSchemes, "/"))
		}
	}
	if s.TLS != nil {
		cn := firstNonEmpty(s.TLS.SubjectCN, s.TLS.Subject)
		if cn != "" {
			parts = append(parts, "cert "+oneLine(cn, 50))
		}
		if s.TLS.Expired {
			parts = append(parts, "certificate expired")
		} else if s.TLS.SelfSigned {
			parts = append(parts, "self-signed")
		}
	}
	if len(parts) == 0 && s.Banner != "" {
		parts = append(parts, oneLine(s.Banner, 80))
	}
	return strings.Join(parts, " · ")
}

func networkIDs(d model.MissionData) []int64 {
	ids := make([]int64, 0, len(d.Networks))
	for _, n := range d.Networks {
		ids = append(ids, n.ID)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	return ids
}

func matrixIndex(d model.MissionData) map[[2]int64]model.MatrixCell {
	out := make(map[[2]int64]model.MatrixCell, len(d.Matrix))
	for _, c := range d.Matrix {
		out[[2]int64{c.SourceNetworkID, c.TargetNetworkID}] = c
	}
	return out
}

func mdCell(src, dst int64, cells map[[2]int64]model.MatrixCell) string {
	if src == dst {
		return "-"
	}
	c, ok := cells[[2]int64{src, dst}]
	if !ok {
		return "not tested"
	}
	if c.Reachable == 0 {
		return fmt.Sprintf("blocked (0/%d)", c.Tested)
	}
	return fmt.Sprintf("**%d/%d reachable**", c.Reachable, c.Tested)
}

func mdEscape(s string) string {
	r := strings.NewReplacer("|", "\\|", "\n", " ", "\r", "")
	return r.Replace(s)
}

func optional(prefix, v string) string {
	if v == "" {
		return ""
	}
	return prefix + v
}

func dedupe(in []string) []string {
	seen := map[string]bool{}
	out := in[:0]
	for _, v := range in {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out
}

