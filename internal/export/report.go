// The Markdown and HTML reports are the human-facing deliverable: an executive
// summary, the inventory per network, the segmentation matrix and the
// findings. They are generated from the same outline so the two stay in sync.

type reportSummary struct {
	Networks     int
	Hosts        int
	Services     int
	Assets       int
	Findings     int
	BySeverity   map[model.Severity]int
	ReachTested  int
	ReachOK      int
	CrossedPairs int
	TopPorts     []portCount
	LastScan     time.Time
}

type portCount struct {
	Port  int
	Proto model.Protocol
	Name  string
	Count int
}

func buildSummary(d model.MissionData) reportSummary {
	s := reportSummary{
		Networks:   len(d.Networks),
		Hosts:      len(d.Hosts),
		Services:   len(d.Services),
		Assets:     len(d.Assets),
		Findings:   len(d.Findings),
		BySeverity: map[model.Severity]int{},
	}
	for _, f := range d.Findings {
		s.BySeverity[f.Severity]++
	}
	for _, r := range d.Reach {
		s.ReachTested++
		if r.Status == model.ReachOpen {
			s.ReachOK++
		}
	}
	for _, c := range d.Matrix {
		if c.Reachable > 0 {
			s.CrossedPairs++
		}
	}
	counts := map[string]*portCount{}
	for _, sv := range d.Services {
		key := fmt.Sprintf("%d/%s", sv.Port, sv.Protocol)
		pc := counts[key]
		if pc == nil {
			pc = &portCount{Port: sv.Port, Proto: sv.Protocol, Name: sv.Name}
			counts[key] = pc
		}
		pc.Count++
		if pc.Name == "" {
			pc.Name = sv.Name
		}
	}
	for _, pc := range counts {
		s.TopPorts = append(s.TopPorts, *pc)
	}
	sort.Slice(s.TopPorts, func(i, j int) bool {
		if s.TopPorts[i].Count != s.TopPorts[j].Count {
			return s.TopPorts[i].Count > s.TopPorts[j].Count
		}
		return s.TopPorts[i].Port < s.TopPorts[j].Port
	})
	if len(s.TopPorts) > 15 {
		s.TopPorts = s.TopPorts[:15]
	}
	for _, sc := range d.Scans {
		if sc.FinishedAt != nil && sc.FinishedAt.After(s.LastScan) {
			s.LastScan = *sc.FinishedAt
		}
	}
	return s
}

