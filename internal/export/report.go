func writeHTML(w io.Writer, d model.MissionData) error {
	sum := buildSummary(d)
	names := networkNames(d)
	byHost := servicesByHost(d)
	cells := matrixIndex(d)
	ids := networkIDs(d)

	e := html.EscapeString
	p := func(format string, args ...any) error {
		_, err := fmt.Fprintf(w, format, args...)
		return err
	}

	title := d.Mission.Name
	if d.Mission.Client != "" {
		title = d.Mission.Client + " - " + d.Mission.Name
	}

	if err := p(htmlHead, e(title)); err != nil {
		return err
	}
	if err := p(`<h1>Internal network review</h1><p class="sub">%s · generated by NETY %s on %s</p>`,
		e(title), e(config.Version), e(d.ExportedAt.Format("2006-01-02 15:04 MST"))); err != nil {
		return err
	}
	if d.Mission.Description != "" {
		if err := p(`<p>%s</p>`, e(d.Mission.Description)); err != nil {
			return err
		}
	}

	// Summary cards.
	if err := p(`<section><h2>Summary</h2><div class="cards">`); err != nil {
		return err
	}
	cards := [][2]string{
		{"Networks", itoa(sum.Networks)},
		{"Live hosts", itoa(sum.Hosts)},
		{"Open services", itoa(sum.Services)},
		{"Machines", itoa(sum.Assets)},
		{"Findings", itoa(sum.Findings)},
	}
	if sum.ReachTested > 0 {
		cards = append(cards, [2]string{"Flows crossing", fmt.Sprintf("%d/%d", sum.ReachOK, sum.ReachTested)})
	}
	for _, c := range cards {
		if err := p(`<div class="card"><div class="n">%s</div><div class="l">%s</div></div>`, e(c[1]), e(c[0])); err != nil {
			return err
		}
	}
	if err := p(`</div>`); err != nil {
		return err
	}
	if sum.Findings > 0 {
		if err := p(`<p class="sevline">`); err != nil {
			return err
		}
		for _, sev := range []model.Severity{model.SevCritical, model.SevHigh, model.SevMedium, model.SevLow, model.SevInfo} {
			if n := sum.BySeverity[sev]; n > 0 {
				if err := p(`<span class="sev sev-%s">%s %d</span> `, sev, strings.ToUpper(string(sev)), n); err != nil {
					return err
				}
			}
		}
		if err := p(`</p>`); err != nil {
			return err
		}
	}
	if err := p(`</section>`); err != nil {
		return err
	}

	// Networks.
	if err := p(`<section><h2>Networks</h2><table><thead><tr><th>Network</th><th>VLAN</th><th>Prefixes</th><th>Gateway</th><th>Hosts</th><th>Services</th></tr></thead><tbody>`); err != nil {
		return err
	}
	hostsPerNet := map[int64]int{}
	svcPerNet := map[int64]int{}
	for _, h := range d.Hosts {
		hostsPerNet[h.NetworkID]++
	}
	for _, s := range d.Services {
		svcPerNet[s.NetworkID]++
	}
	for _, n := range d.Networks {
		vlan := "-"
		if n.VLANID != 0 {
			vlan = itoa(n.VLANID)
		}
		if err := p(`<tr><td>%s</td><td>%s</td><td class="mono">%s</td><td class="mono">%s</td><td>%d</td><td>%d</td></tr>`,
			e(n.Name), vlan, e(strings.Join(n.Prefixes, ", ")), e(firstNonEmpty(n.Gateway, "-")),
			hostsPerNet[n.ID], svcPerNet[n.ID]); err != nil {
			return err
		}
	}
	if err := p(`</tbody></table>`); err != nil {
		return err
	}
	for _, n := range d.Networks {
		if n.L2.DTPSeen {
			if err := p(`<p class="warn"><strong>%s</strong>: the switch port negotiates trunking (DTP mode <code>%s</code>). A trunk may be obtainable from this socket, which would defeat the VLAN separation.</p>`,
				e(n.Name), e(n.L2.DTPMode)); err != nil {
				return err
			}
		}
	}
	if err := p(`</section>`); err != nil {
		return err
	}

	// Matrix.
	if len(d.Matrix) > 0 {
		if err := p(`<section><h2>Segmentation matrix</h2><p>Services reachable from each source network.</p><table class="matrix"><thead><tr><th>source \ target</th>`); err != nil {
			return err
		}
		for _, id := range ids {
			if err := p(`<th>%s</th>`, e(netName(names, id))); err != nil {
				return err
			}
		}
		if err := p(`</tr></thead><tbody>`); err != nil {
			return err
		}
		for _, src := range ids {
			if err := p(`<tr><th>%s</th>`, e(netName(names, src))); err != nil {
				return err
			}
			for _, dst := range ids {
				class, text := htmlCell(src, dst, cells)
				if err := p(`<td class="%s">%s</td>`, class, e(text)); err != nil {
					return err
				}
			}
			if err := p(`</tr>`); err != nil {
				return err
			}
		}
		if err := p(`</tbody></table>`); err != nil {
			return err
		}

		crossed := filter(d.Reach, func(r model.ReachResult) bool { return r.Status == model.ReachOpen })
		if len(crossed) > 0 {
			services := serviceIndex(d)
			if err := p(`<h3>Flows that crossed the segmentation</h3><table><thead><tr><th>From</th><th>Target</th><th>Service</th><th>Technique</th></tr></thead><tbody>`); err != nil {
				return err
			}
			for _, r := range crossed {
				svc := ""
				if s, ok := services[r.TargetServiceID]; ok {
					svc = firstNonEmpty(serviceLabel(s), s.Name)
				}
				target := r.IP
				if r.Port != 0 {
					target = fmt.Sprintf("%s:%d/%s", r.IP, r.Port, r.Protocol)
				}
				if err := p(`<tr><td>%s</td><td class="mono">%s</td><td>%s</td><td><code>%s</code></td></tr>`,
					e(netName(names, r.SourceNetworkID)), e(target), e(svc), e(r.Technique)); err != nil {
					return err
				}
			}
			if err := p(`</tbody></table>`); err != nil {
				return err
			}
		}
		if err := p(`</section>`); err != nil {
			return err
		}
	}

	// Findings.
	if len(d.Findings) > 0 {
		if err := p(`<section><h2>Findings</h2>`); err != nil {
			return err
		}
		for _, f := range d.Findings {
			loc := f.IP
			if f.Port != 0 {
				loc = fmt.Sprintf("%s:%d/%s", f.IP, f.Port, f.Protocol)
			}
			if err := p(`<article class="finding"><h3><span class="sev sev-%s">%s</span> %s</h3><p class="mono loc">%s</p>`,
				f.Severity, strings.ToUpper(string(f.Severity)), e(f.Title), e(loc)); err != nil {
				return err
			}
			if f.Description != "" {
				if err := p(`<p>%s</p>`, e(f.Description)); err != nil {
					return err
				}
			}
			if f.Evidence != "" {
				if err := p(`<pre>%s</pre>`, e(strings.TrimSpace(f.Evidence))); err != nil {
					return err
				}
			}
			if f.Remediation != "" {
				if err := p(`<p><strong>Remediation.</strong> %s</p>`, e(f.Remediation)); err != nil {
					return err
				}
			}
			if err := p(`</article>`); err != nil {
				return err
			}
		}
		if err := p(`</section>`); err != nil {
			return err
		}
	}

	// Inventory.
	if err := p(`<section><h2>Inventory</h2>`); err != nil {
		return err
	}
	for _, n := range d.Networks {
		hosts := filter(d.Hosts, func(h model.Host) bool { return h.NetworkID == n.ID })
		if len(hosts) == 0 {
			continue
		}
		if err := p(`<h3>%s</h3><table><thead><tr><th>Host</th><th>Address</th><th>OS / vendor</th><th>Open services</th></tr></thead><tbody>`, e(n.Name)); err != nil {
			return err
		}
		for _, h := range hosts {
			var svc []string
			for _, s := range byHost[h.ID] {
				label := fmt.Sprintf("%d/%s", s.Port, s.Protocol)
				if name := firstNonEmpty(serviceLabel(s), s.Name); name != "" {
					label += " " + name
				}
				svc = append(svc, label)
			}
			if err := p(`<tr><td>%s</td><td class="mono">%s</td><td>%s</td><td class="mono small">%s</td></tr>`,
				e(hostLabel(h)), e(h.IP), e(strings.TrimSpace(h.OS+" "+h.Vendor)),
				e(strings.Join(svc, " · "))); err != nil {
				return err
			}
		}
		if err := p(`</tbody></table>`); err != nil {
			return err
		}
	}
	if err := p(`</section>`); err != nil {
		return err
	}

	_, err := io.WriteString(w, htmlFoot)
	return err
}

func htmlCell(src, dst int64, cells map[[2]int64]model.MatrixCell) (string, string) {
	if src == dst {
		return "self", "-"
	}
	c, ok := cells[[2]int64{src, dst}]
	if !ok {
		return "untested", "not tested"
	}
	if c.Reachable == 0 {
		return "blocked", fmt.Sprintf("blocked (0/%d)", c.Tested)
	}
	return "open", fmt.Sprintf("%d/%d reachable", c.Reachable, c.Tested)
}

